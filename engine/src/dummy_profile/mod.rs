//! Dummy System Profile Module
//!
//! Provides a fake system profile mode that spoofs all hardware/software
//! fingerprinting signals. Users select from a curated list of 50+ real
//! device profiles (GPU, CPU, screen resolution, etc.) rather than writing
//! their own values. This ensures internal coherence — a Windows 11 profile
//! with an NVIDIA GPU reports matching values across every signal.
//!
//! Spoofed vectors:
//!   - GPU vendor + renderer (WebGL UNMASKED_VENDOR/RENDERER)
//!   - CPU brand + hardware concurrency
//!   - Device memory (RAM)
//!   - Screen resolution + color depth + pixel ratio
//!   - Platform / OS / OS version
//!   - User-Agent + Client Hints (coherent with selected device)
//!   - Timezone + locale
//!   - WebRTC IP leak prevention
//!   - Font list (coherent with OS)
//!   - AudioContext sample rate + channel count

use serde::{Deserialize, Serialize};
use once_cell::sync::Lazy;
use std::collections::HashMap;
use std::sync::Mutex;

/// A complete real device profile for dummy mode selection.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DeviceProfile {
    /// Display name shown in the UI selection list.
    pub name: String,
    /// Short identifier for internal use.
    pub id: String,
    /// Operating system name.
    pub os: String,
    /// OS version string.
    pub os_version: String,
    /// Platform string (navigator.platform).
    pub platform: String,
    /// CPU brand string.
    pub cpu_brand: String,
    /// Number of logical CPU cores.
    pub hardware_concurrency: u32,
    /// Device memory in GB (capped at 8 for navigator.deviceMemory).
    pub device_memory_gb: f32,
    /// GPU vendor (NVIDIA, AMD, Intel, Apple, Qualcomm, ARM).
    pub gpu_vendor: String,
    /// GPU renderer string (WebGL UNMASKED_RENDERER_WEBGL).
    pub gpu_renderer: String,
    /// Screen width in CSS pixels.
    pub screen_width: u32,
    /// Screen height in CSS pixels.
    pub screen_height: u32,
    /// Color depth in bits.
    pub color_depth: u32,
    /// Device pixel ratio.
    pub device_pixel_ratio: f32,
    /// Timezone.
    pub timezone: String,
    /// Locale (language tag).
    pub locale: String,
    /// Touch support available.
    pub touch_support: bool,
    /// Common system fonts for this OS.
    pub fonts: Vec<String>,
    /// User-Agent string (coherent with all above values).
    pub user_agent: String,
    /// Sec-CH-UA client hint value.
    pub sec_ch_ua: String,
    /// Sec-CH-UA-Platform client hint value.
    pub sec_ch_ua_platform: String,
    /// Sec-CH-UA-Platform-Version client hint value.
    pub sec_ch_ua_platform_version: String,
    /// Sec-CH-UA-Mobile client hint value.
    pub sec_ch_ua_mobile: String,
    /// Sec-CH-UA-Arch client hint value.
    pub sec_ch_ua_arch: String,
    /// Sec-CH-UA-Model client hint value.
    pub sec_ch_ua_model: String,
    /// WebGL version string.
    pub webgl_version: String,
    /// WebGL shading language version.
    pub webgl_shading_language: String,
}

