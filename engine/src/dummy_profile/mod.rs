/// Dummy system profile configuration — applied to a browser profile.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DummySystemConfig {
    /// Whether dummy mode is enabled.
    pub enabled: bool,
    /// The selected device profile.
    pub device: Option<DeviceProfile>,
}

impl Default for DummySystemConfig {
    fn default() -> Self {
        Self {
            enabled: false,
            device: None,
        }
    }
}

/// Get or create a dummy system config for a browser profile.
pub fn get_config(profile_id: &str) -> DummySystemConfig {
    let store = DUMMY_PROFILE_STORE.lock().unwrap();
    store.get(profile_id).cloned().unwrap_or_default()
}

/// Set the dummy system config for a browser profile.
pub fn set_config(profile_id: &str, config: DummySystemConfig) {
    let mut store = DUMMY_PROFILE_STORE.lock().unwrap();
    store.insert(profile_id.to_string(), config);
}

/// Remove dummy config when profile is deleted.
pub fn remove_config(profile_id: &str) {
    let mut store = DUMMY_PROFILE_STORE.lock().unwrap();
    store.remove(profile_id);
}

/// Apply dummy system fingerprint spoofing to HTTP headers.
pub fn apply_to_headers(profile_id: &str, headers: &mut HashMap<String, String>) {
    let config = get_config(profile_id);
    if !config.enabled {
        return;
    }
    if let Some(device) = &config.device {
        headers.insert("User-Agent".to_string(), device.user_agent.clone());
        headers.insert("Accept-Language".to_string(), device.locale.clone());
        headers.insert("Sec-CH-UA".to_string(), device.sec_ch_ua.clone());
        headers.insert(
            "Sec-CH-UA-Mobile".to_string(),
            device.sec_ch_ua_mobile.clone(),
        );
        headers.insert(
            "Sec-CH-UA-Platform".to_string(),
            device.sec_ch_ua_platform.clone(),
        );
        headers.insert(
            "Sec-CH-UA-Platform-Version".to_string(),
            device.sec_ch_ua_platform_version.clone(),
        );
        headers.insert(
            "Sec-CH-UA-Arch".to_string(),
            device.sec_ch_ua_arch.clone(),
        );
        headers.insert(
            "Sec-CH-UA-Model".to_string(),
            device.sec_ch_ua_model.clone(),
        );
    }
}

